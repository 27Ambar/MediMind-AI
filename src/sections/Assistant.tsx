import { useEffect, useRef, useState } from 'react'
import Icon from '../components/Icon'
import { Badge, SectionHeading } from '../components/UI'
import { FAQ, demoAnswer } from '../data/faq'

type Msg = { role: 'user' | 'assistant'; text: string }
type Mode = 'checking' | 'demo' | 'live'

const SUGGESTED = [FAQ[0].q, FAQ[3].q, FAQ[6].q, FAQ[11].q]

export default function Assistant() {
  const [mode, setMode] = useState<Mode>('checking')
  const [msgs, setMsgs] = useState<Msg[]>([])
  const [input, setInput] = useState('')
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')
  const logRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    const ctrl = new AbortController()
    fetch('/api/status', { signal: ctrl.signal })
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error('status'))))
      .then((d: { live?: boolean }) => setMode(d.live ? 'live' : 'demo'))
      .catch(() => setMode('demo'))
    return () => ctrl.abort()
  }, [])
  // Scroll only the chat box itself (never the whole page) and only once a conversation exists.
  useEffect(() => {
    const el = logRef.current
    if (el && msgs.length > 0) el.scrollTop = el.scrollHeight
  }, [msgs, busy])

  const send = async (text: string) => {
    const t = text.trim()
    if (!t || busy) return
    setError('')
    const next: Msg[] = [...msgs, { role: 'user', text: t }]
    setMsgs(next)
    setInput('')
    if (mode !== 'live') {
      setMsgs([...next, { role: 'assistant', text: demoAnswer(t).text }])
      return
    }
    setBusy(true)
    try {
      const r = await fetch('/api/chat', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ messages: next.slice(-8) }) })
      const d = (await r.json()) as { reply?: string; error?: string }
      if (!r.ok || !d.reply) throw new Error(d.error || 'The assistant could not answer.')
      setMsgs([...next, { role: 'assistant', text: d.reply }])
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Something went wrong.')
    } finally {
      setBusy(false)
    }
  }

  return (
    <section id="ask" className="section alt" aria-labelledby="ask-title">
      <div className="container narrow">
        <SectionHeading eyebrow="Ask MediMind" title="Questions about healthcare AI?">
          Ask about imaging, drug discovery, genetics, patient care or ethics. This assistant explains concepts; it never diagnoses or advises on treatment.
        </SectionHeading>
        <h3 id="ask-title" className="sr-only">Ask MediMind assistant</h3>
        <div className="card chat">
          <div className="chat-head">
            {mode === 'checking' && <Badge tone="grey">Checking mode...</Badge>}
            {mode === 'demo' && <Badge tone="amber">Demo mode: scripted answers, no AI model running</Badge>}
            {mode === 'live' && <Badge tone="mint">Live AI mode: generated by a language model, may contain errors</Badge>}
          </div>
          <div ref={logRef} className="chat-log" role="log" aria-live="polite" aria-label="Conversation">
            {msgs.length === 0 && <p className="muted">Try a suggested question or type your own.</p>}
            {msgs.map((m, i) => <div key={i} className={`msg ${m.role}`}><span className="sr-only">{m.role === 'user' ? 'You: ' : 'MediMind: '}</span>{m.text}</div>)}
            {busy && <div className="msg assistant">Thinking...</div>}
            {error && <div className="msg error" role="alert">{error}</div>}
          </div>
          <div className="chips" aria-label="Suggested questions" role="group">
            {SUGGESTED.map((s) => <button key={s} className="chip" disabled={busy} onClick={() => send(s)}>{s}</button>)}
          </div>
          <form className="chat-form" onSubmit={(e) => { e.preventDefault(); send(input) }}>
            <label htmlFor="ask-input" className="sr-only">Your question</label>
            <input id="ask-input" value={input} maxLength={400} onChange={(e) => setInput(e.target.value)} placeholder="Ask a general question about healthcare AI" autoComplete="off" />
            <button className="btn primary" type="submit" disabled={busy || !input.trim()}><Icon name="send" size={16} /> Send</button>
          </form>
          <p className="muted small-text">Do not enter personal medical information. For personal health concerns, contact a qualified healthcare professional.</p>
        </div>
      </div>
    </section>
  )
}
